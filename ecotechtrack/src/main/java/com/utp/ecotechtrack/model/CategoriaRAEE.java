package com.utp.ecotechtrack.model;

/**
 * Clasificación oficial de Residuos de Aparatos Eléctricos y Electrónicos (RAEE).
 */
public enum CategoriaRAEE {
    EQUIPOS_INFORMATICA_Y_TELECOMUNICACIONES, // Computadoras, laptops, impresoras, servidores
    APARATOS_ELECTRONICOS_DE_CONSUMO,        // Monitores, televisores, cámaras
    GRANDES_ELECTRODOMESTICOS,                // Servidores en rack, equipos de climatización
    PEQUENOS_ELECTRODOMESTICOS,               // Periféricos, cargadores, fuentes de poder
    BATERIAS_Y_ACUMULADORES,                  // Baterías de litio, UPS, baterías de respaldo
    HERRAMIENTAS_ELECTRICAS_Y_ELECTRONICAS    // Equipos de laboratorio y mantenimiento
}
